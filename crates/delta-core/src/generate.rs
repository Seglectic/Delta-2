//! Turn a [`Config`] into the files the system runs: xremap config, KWin script,
//! and systemd units. Pure functions; writing and reloading live in `system`.
//!
//! Output matches the legacy bash generator byte for byte (apart from the KWin
//! header comment); `tests/golden.rs` checks this against its recorded output.

use crate::config::{Action, Binding, Config, Layer};
use std::fmt::Write;

const KWIN_FUNCS: &str = include_str!("../templates/kwin_funcs.js");

/// Header comment at the top of the generated KWin script. Three lines, so the golden
/// test can skip it when comparing against the legacy header.
pub const KWIN_HEADER: &str = "\
// Delta Tile — KWin script
// Generated by delta from ~/.config/delta/delta.toml.
// Edit that file (or use the Delta app), not this one.
";

/// xremap's name for the delta modifier key.
fn xremap_modifier(config: &Config) -> String {
    match config.engine.modifier_key.to_lowercase().as_str() {
        "capslock" => "CapsLock".into(),
        "f20" => "F20".into(),
        _ => config.engine.modifier_key.clone(),
    }
}

/// KDE shortcut key name: single letters upper-case, everything else as written.
fn kde_key(key: &str) -> String {
    if key.chars().count() == 1 { key.to_uppercase() } else { key.into() }
}

/// xremap chord syntax uses `-` where Delta config uses `+`.
fn xremap_chord(send: &str) -> String {
    send.replace('+', "-")
}

pub fn xremap_config(config: &Config) -> String {
    let m = xremap_modifier(config);
    let mut out = String::new();
    writeln!(out, "virtual_modifiers:\n  - {m}\n\nkeymap:\n  - name: delta-layer").unwrap();

    // Delta layer, all apps: window actions become the Ctrl+Alt+Meta chord KDE
    // listens for; key actions send their chord directly.
    let delta: Vec<&Binding> =
        config.bindings.iter().filter(|b| b.layer == Layer::Delta && b.only_in.is_none()).collect();
    if delta.is_empty() {
        out.push_str("    remap: {}\n");
    } else {
        out.push_str("    remap:\n");
        for b in delta {
            let key = b.key.to_lowercase();
            let target = match &b.action {
                Action::Keys { send } => xremap_chord(send),
                _ => format!("C-A-Super-{key}"),
            };
            writeln!(out, "      {m}-{key}: {target}").unwrap();
        }
    }

    // Base layer, all apps: plain remaps. (Base-layer window actions need no
    // xremap entry: KDE catches the bare key itself.)
    let global: Vec<&Binding> = config
        .bindings
        .iter()
        .filter(|b| b.layer == Layer::Base && b.only_in.is_none() && !b.action.is_window_action())
        .collect();
    if !global.is_empty() {
        out.push_str("\n  - name: global-keys\n    remap:\n");
        for b in global {
            if let Action::Keys { send } = &b.action {
                writeln!(out, "      {}: {}", b.key, xremap_chord(send)).unwrap();
            }
        }
    }

    // Per-app blocks, one per app in order of first appearance
    let mut apps: Vec<&str> = Vec::new();
    for b in &config.bindings {
        if let Some(app) = &b.only_in
            && !apps.contains(&app.as_str())
        {
            apps.push(app);
        }
    }
    for app in apps {
        write!(out, "\n  - name: {app}-appkeys\n    application:\n      only: [\"{app}\"]\n    remap:\n").unwrap();
        for b in config.bindings.iter().filter(|b| b.only_in.as_deref() == Some(app)) {
            let Action::Keys { send } = &b.action else { continue };
            let key = match b.layer {
                Layer::Base => b.key.clone(),
                Layer::Delta => format!("{m}-{}", b.key.to_lowercase()),
            };
            writeln!(out, "      {key}: {}", xremap_chord(send)).unwrap();
        }
    }
    out
}

pub fn kwin_script(config: &Config) -> String {
    let mut out = String::from(KWIN_HEADER);
    out.push_str("\nvar windowOverrides = {};\n");
    for o in &config.overrides {
        let app = &o.app;
        writeln!(out, "if (!windowOverrides[\"{app}\"]) windowOverrides[\"{app}\"] = {{}};").unwrap();
        writeln!(out, "windowOverrides[\"{app}\"][\"{}\"] = [{}, {}];", o.key.to_lowercase(), o.x, o.width).unwrap();
    }

    let g = &config.guards;
    let js_list =
        |items: &[String]| -> String { items.iter().map(|s| format!("\"{s}\"")).collect::<Vec<_>>().join(",") };
    writeln!(out, "var deltaDebug = false;").unwrap();
    writeln!(out, "var ignoreFullscreen = {};", g.ignore_fullscreen).unwrap();
    writeln!(out, "var ignoredDesktopFiles = [{}];", js_list(&g.ignored_desktop_files)).unwrap();
    writeln!(out, "var ignoredClasses = [{}];", js_list(&g.ignored_classes)).unwrap();

    out.push_str(KWIN_FUNCS);

    for b in config.bindings.iter().filter(|b| b.only_in.is_none()) {
        let call = match &b.action {
            Action::Tile { layout, side } => {
                format!("tileIntoLayout(\"{}\", \"{}\")", layout.as_str(), side.as_str())
            }
            Action::Span { x, width, name } => {
                let name = name.clone().unwrap_or_else(|| b.key.to_lowercase());
                format!("tile(\"{name}\", {x}, {width})")
            }
            Action::Fixed { width, height } => format!("tileFixed({width}, {height})"),
            Action::App { app } => format!("focusOrLaunch(\"{app}\")"),
            Action::Keys { .. } => continue,
        };
        let shortcut = match b.layer {
            Layer::Delta => format!("Ctrl+Alt+Meta+{}", kde_key(&b.key)),
            Layer::Base => kde_key(&b.key),
        };
        writeln!(out, "registerShortcut(\"{}\", \"{}\", \"{shortcut}\", function() {{ {call}; }});", b.id, b.label())
            .unwrap();
    }
    out
}

/// The `delta-launch@.service` template. KWin starts `delta-launch@<app>.service`
/// over D-Bus to launch an app, so it runs outside KWin's process tree.
pub fn launcher_unit(exec_start: &str) -> String {
    format!("[Unit]\nDescription=Delta app launcher for %i\n\n[Service]\nType=oneshot\nExecStart={exec_start} %i\n")
}

pub fn xremap_service(config: &Config, xremap_bin: &str, xremap_config_path: &str) -> String {
    let mut args = String::from(" --watch=device");
    for dev in &config.xremap.ignore_devices {
        let escaped = dev.replace('\\', "\\\\").replace('"', "\\\"");
        write!(args, " --ignore \"{escaped}\"").unwrap();
    }
    format!(
        "[Unit]\nDescription=xremap key remapper (delta modifier)\n\n[Service]\nExecStart={xremap_bin}{args} {xremap_config_path}\nRestart=on-failure\n\n[Install]\nWantedBy=default.target\n"
    )
}
